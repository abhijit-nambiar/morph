#!/usr/bin/env python3
"""Compare existing renderers on independent styled targets with a fixed split."""
import argparse
import json
from pathlib import Path

import numpy as np

import cubic_color
import gamut_renderer
import morph
import poly_color


CANDIDATES = {
    'gamut': {'renderer': 'gamut', 'regularization': 0},
    'polynomial-1e-5': {'renderer': 'polynomial', 'regularization': 1e-5},
    'polynomial-1e-3': {'renderer': 'polynomial', 'regularization': 1e-3},
    'cubic-1e-6': {'renderer': 'cubic', 'regularization': 1e-6},
    'cubic-1e-5': {'renderer': 'cubic', 'regularization': 1e-5},
}


def split_group(group):
    """Choose roles using only membership and names, before any target scores."""
    others = sorted(p for p in group['photos'] if p != group['representative'])
    validation = others[:1] if len(group['photos']) >= 4 else []
    return {p: ('fit' if p == group['representative'] else
                'validation' if p in validation else 'test') for p in group['photos']}


def fit_candidate(name, x, y):
    spec = CANDIDATES[name]
    if spec['renderer'] == 'gamut':
        weights, metrics = gamut_renderer.fit(x, y)
        return weights, metrics, gamut_renderer.render
    model = cubic_color if spec['renderer'] == 'cubic' else poly_color
    weights, metrics = model.fit(x, y, regularization=spec['regularization'])
    return weights, metrics, model.render


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('groups')
    parser.add_argument('styles')
    parser.add_argument('--size', type=int, default=512)
    parser.add_argument('--out', required=True)
    args = parser.parse_args()
    if not 64 <= args.size <= 1024:
        raise ValueError('size must be 64–1024')
    groups = morph.validate_groups(json.loads(Path(args.groups).read_text()))
    styles = json.loads(Path(args.styles).read_text())
    paths = [p for group in groups for p in group['photos']]
    morph.protect_inputs([args.groups, args.styles] + paths, [args.out])
    morph.protect_existing([args.out], False)
    cache = {p: morph.load(p, args.size) for p in paths}
    rows, fits = [], []
    splits = {g['id']: split_group(g) for g in groups}
    for style_id, style in styles.items():
        targets = {p: morph.pillow_soft_target(x, 'neutral', style['settings'])
                   for p, x in cache.items()}
        for group in groups:
            rep = group['representative']
            for candidate in CANDIDATES:
                weights, metrics, render = fit_candidate(candidate, cache[rep], targets[rep])
                fits.append({'style': style_id, 'scene': group['id'],
                             'candidate': candidate, 'metrics': metrics})
                for path in group['photos']:
                    source, target = cache[path], targets[path]
                    predicted = render(source, weights)
                    rows.append({'style': style_id, 'scene': group['id'],
                                 'photo': path, 'role': splits[group['id']][path],
                                 'candidate': candidate,
                                 'source_rmse': float(np.sqrt(np.mean((source-target)**2))),
                                 'output_rmse': float(np.sqrt(np.mean((predicted-target)**2))),
                                 'max_error': float(np.max(np.abs(predicted-target)))})
            print(style_id, group['id'], 'benchmarked', flush=True)
    validation = {}
    for candidate in CANDIDATES:
        values = [r['output_rmse'] for r in rows
                  if r['candidate'] == candidate and r['role'] == 'validation']
        if not values:
            raise ValueError('Need scenes with at least four photos for validation')
        validation[candidate] = float(np.mean(values))
    selected = min(validation, key=validation.get)
    summaries = []
    for style in styles:
        for candidate in CANDIDATES:
            subset = [r for r in rows if r['style'] == style and
                      r['candidate'] == candidate and r['role'] == 'test']
            summaries.append({'style': style, 'candidate': candidate,
                              'test_photos': len(subset),
                              'source_mean_rmse': float(np.mean([r['source_rmse'] for r in subset])),
                              'output_mean_rmse': float(np.mean([r['output_rmse'] for r in subset])),
                              'output_p95_rmse': float(np.percentile([r['output_rmse'] for r in subset], 95)),
                              'improved': sum(r['output_rmse'] < r['source_rmse'] for r in subset)})
    morph.dump({'scope': 'Same-album controlled targets generated by independent Pillow tone LUTs '
                'and HSV color adjustments. One representative per scene is fitted. The first other '
                'filename in scenes with at least four photos is validation; all remaining photos '
                'are test. One renderer is selected across styles using validation means only. '
                'No human-edit, mask, artistic-quality or unseen-album claim. Metrics are reduced '
                'resolution before JPEG export.',
                'size': args.size, 'candidates': CANDIDATES, 'splits': splits,
                'source_manifest': {p: morph.sha256_file(p) for p in paths},
                'validation_mean_rmse': validation, 'selected': selected,
                'selected_spec': CANDIDATES[selected], 'summaries': summaries,
                'fits': fits, 'photos': rows}, args.out)
    print('Validation means:', validation, 'Selected:', selected, flush=True)


if __name__ == '__main__':
    main()
