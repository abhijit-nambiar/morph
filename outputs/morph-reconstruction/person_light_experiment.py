#!/usr/bin/env python3
"""Reconstruct a controlled subject-light edit and transfer it within two sample groups."""
import json
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw
import morph,poly_color,prompt_target

ROOT=Path('outputs/morph-reconstruction');MASKS=ROOT/'segmentation-scene-02';SIZE=256;REG=1e-5

def load_mask(p,shape):
 mask=Image.open(MASKS/(Path(p).stem+'-mask.png')).convert('L').resize((shape[1],shape[0]),Image.Resampling.BILINEAR)
 return np.asarray(mask,dtype=np.float32)/255

def features(x,m):
 return np.concatenate([poly_color.features(x),(m[...,None]*x*(1-x)),m[...,None]],axis=-1)

def fit(x,y,m,local):
 f=features(x,m) if local else poly_color.features(x);a=f.reshape(-1,f.shape[-1]).astype('float64');b=(y-x).reshape(-1,3).astype('float64');rng=np.random.default_rng(0);idx=rng.choice(len(a),min(30000,len(a)),replace=False);a=a[idx];b=b[idx];return np.linalg.lstsq(a.T@a/len(a)+REG*np.eye(a.shape[1]),a.T@b/len(a),rcond=None)[0]

def render(x,m,w,local):return np.clip(x+(features(x,m) if local else poly_color.features(x))@w,0,1)
def target(x,m,settings):
 base=morph.pillow_soft_target(x,'neutral',settings);return np.clip(base+m[...,None]*.24*base*(1-base),0,1)
def rmse(a,b,weights=None):
 e=(a-b)**2
 if weights is None:return float(np.sqrt(np.mean(e)))
 if weights.sum()<1:return None
 return float(np.sqrt(np.sum(e*weights[...,None])/(3*weights.sum())))

groups=json.load(open(ROOT/'groups-example-split.json'))['groups'];groups=[g for g in groups if g['id'] in ('scene-02-lawn','scene-02')];settings,interpretation=prompt_target.parse('warm and slightly soft contrast and lift shadows');rows=[];scenes=[];previews=[]
for group in groups:
 rep=group['representative'];x=morph.load(rep,SIZE);m=load_mask(rep,x.shape);y=target(x,m,settings);w0=fit(x,y,m,False);w1=fit(x,y,m,True);held=[]
 for photo in group['photos']:
  if photo==rep:continue
  x=morph.load(photo,SIZE);m=load_mask(photo,x.shape);y=target(x,m,settings);global_img=render(x,m,w0,False);local_img=render(x,m,w1,True)
  row={'scene':group['id'],'photo':photo,'mask_fraction_mean':float(m.mean()),'source_rmse':rmse(x,y),'global_rmse':rmse(global_img,y),'person_aware_rmse':rmse(local_img,y),'global_subject_weighted_rmse':rmse(global_img,y,m),'person_subject_weighted_rmse':rmse(local_img,y,m),'global_background_weighted_rmse':rmse(global_img,y,1-m),'person_background_weighted_rmse':rmse(local_img,y,1-m)};held.append(row);rows.append(row)
  if len([p for p in previews if p[0]==group['id']])<2:previews.append((group['id'],Path(photo).name,[x,y,global_img,local_img]))
 scenes.append({'scene':group['id'],'representative':rep,'heldout':len(held),'global_weights':w0.tolist(),'person_weights':w1.tolist()});print(group['id'],len(held),'held out')
sheet=Image.new('RGB',(1200,50+len(previews)*220),'white');draw=ImageDraw.Draw(sheet)
for j,label in enumerate(['Original','Synthetic target','Global reconstruction','Mask-aware reconstruction']):draw.text((j*300+5,5),label,fill='black')
for i,(scene,name,images) in enumerate(previews):
 draw.text((5,30+i*220),scene+' / '+name,fill='black')
 for j,im in enumerate(images):
  im=Image.fromarray(np.uint8(np.clip(im*255+.5,0,255)));im.thumbnail((285,190));sheet.paste(im,(j*300+5+(285-im.width)//2,50+i*220))
sheet.save(ROOT/'person-light-synthetic-review.jpg',quality=94)
g=np.array([r['global_rmse'] for r in rows]);l=np.array([r['person_aware_rmse'] for r in rows]);summary={'heldout':len(rows),'global_mean_rmse':float(g.mean()),'person_mean_rmse':float(l.mean()),'person_lower':int(np.sum(l<g)),'person_higher':int(np.sum(l>g)),'global_subject_weighted_mean_rmse':float(np.mean([r['global_subject_weighted_rmse'] for r in rows])),'person_subject_weighted_mean_rmse':float(np.mean([r['person_subject_weighted_rmse'] for r in rows]))}
morph.dump({'scope':'Controlled same-album test on two manually selected groups. Targets are generated by a separate Pillow tone/color renderer plus a soft person-mask brightness curve. Both target and reconstruction use the same masks, so this cannot validate mask quality or generalize to actual human edits. Mask accuracy, photo alignment and aesthetics are not evaluated. Inputs and target are sampled at 256 pixels maximum dimension; held-out photos were excluded from fitting.','prompt':'warm and slightly soft contrast and lift shadows, plus synthetic person brightening','size':SIZE,'regularization':REG,'summary':summary,'scenes':scenes,'photos':rows},ROOT/'person-light-synthetic-experiment.json');print(json.dumps(summary,indent=2))
